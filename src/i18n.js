let lang = 'zh';
export function setLang(l) {
  lang = STR[l] ? l : 'zh';
  document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
}
export const getLang = () => lang;
export const t = () => STR[lang];

export function timeAgo(sec, nowSec = Date.now() / 1000) {
  const s = t().ago;
  const d = Math.max(0, nowSec - sec);
  if (d < 60) return s.now;
  if (d < 3600) return s.m(Math.floor(d / 60));
  if (d < 86400) return s.h(Math.floor(d / 3600));
  return s.d(Math.floor(d / 86400));
}
